#!/usr/bin/env python3

# The instance files of the QPN products (mmvq-qpn-impl.cuh): one file per launch entry point, or per pair of types for the
# two-product kernels, so that ptxas compiles them in parallel. Run from this directory.

from glob import glob
import os

TYPES    = ["GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q6_K", "GGML_TYPE_IQ4_XS", "GGML_TYPE_IQ4_NL", "GGML_TYPE_Q3_K", "GGML_TYPE_Q8_0"]
TYPES_2  = TYPES[:6]  # qpn_type_idx order
TYPES_3  = ["GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_IQ4_XS"]  # qpn3_t0_ok
TYPES_AB = TYPES[:5]

HEAD = """// This file has been autogenerated by generate_qpn_cu_files.py, do not edit manually.

#include "../mmvq-qpn-impl.cuh"

"""


def name(t):
    return t[len("GGML_TYPE_"):].lower()


def write(fname, lines):
    with open(fname, "w") as f:
        f.write(HEAD + "\n".join(lines) + "\n")


for f in glob("mmvq-qpn*.cu"):
    os.remove(f)

for t in TYPES:
    write(f"mmvq-qpn-instance-{name(t)}.cu", [f"DECL_QPN_CASE({t});"])

# a pair and its reverse (an abort, the caller orders pairs by type) share a file
for i, a in enumerate(TYPES_2):
    for b in TYPES_2[i:]:
        cases = [f"DECL_QPN2_CASE({a}, {b});"] + ([f"DECL_QPN2_CASE({b}, {a});"] if a != b else [])
        write(f"mmvq-qpn2-instance-{name(a)}-{name(b)}.cu", cases)

for t in TYPES_3:
    write(f"mmvq-qpn3-instance-{name(t)}.cu", [f"DECL_QPN3_CASE({t});"])

for t in TYPES_AB:
    write(f"mmvq-qpnab-instance-{name(t)}.cu", [f"DECL_QPN2AB_CASE({t});", f"DECL_QPN4AB_CASE({t});"])
